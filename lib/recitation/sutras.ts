export const MORNING_START_HOUR = 4;
export const MORNING_END_HOUR = 8;
export const EVENING_START_HOUR = 18;
export const EVENING_END_HOUR = 22;

export function isMorningTime(): boolean {
  const hour = new Date().getHours();
  return hour >= MORNING_START_HOUR && hour < MORNING_END_HOUR;
}

export function isEveningTime(): boolean {
  const hour = new Date().getHours();
  return hour >= EVENING_START_HOUR && hour < EVENING_END_HOUR;
}

export function isSessionTime(session: 'morning' | 'evening'): boolean {
  return session === 'morning' ? isMorningTime() : isEveningTime();
}

export function getSessionTimeRange(session: 'morning' | 'evening'): string {
  if (session === 'morning') {
    return `${MORNING_START_HOUR}:00 - ${MORNING_END_HOUR}:00`;
  }
  return `${EVENING_START_HOUR}:00 - ${EVENING_END_HOUR}:00`;
}